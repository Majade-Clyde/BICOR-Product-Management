    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    CONSTRAINT check_dashboard_theme CHECK (dashboard_theme IN ('light', 'system', 'dark')),
    CONSTRAINT singleton_settings_id CHECK (id = 1)
);

