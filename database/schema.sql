-- ==============================================================================
-- 7. ADMINISTRATOR AUTHENTICATION & USER PROFILE SCHEMA
-- ==============================================================================
-- Description: Maps Supabase Auth user accounts with the predefined administrator 
--              profile (Username: Adminclyde).
-- ==============================================================================

-- Create admin_profiles table linked to Supabase auth.users
CREATE TABLE IF NOT EXISTS admin_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    username TEXT NOT NULL UNIQUE DEFAULT 'Adminclyde',
    email TEXT NOT NULL UNIQUE,
    full_name TEXT DEFAULT 'System Administrator',
    role TEXT NOT NULL DEFAULT 'Administrator',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable RLS for security
ALTER TABLE admin_profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated read on admin_profiles"
ON admin_profiles FOR SELECT
USING (auth.uid() = id);

CREATE POLICY "Allow service_role full access on admin_profiles"
ON admin_profiles FOR ALL
USING (true)
WITH CHECK (true);

-- Auto-sync Trigger: Automatically link newly created Supabase Auth users to admin_profiles
CREATE OR REPLACE FUNCTION public.handle_new_admin_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.admin_profiles (id, username, email, full_name, role)
    VALUES (
        NEW.id,
        'Adminclyde',
        NEW.email,
        'Administrator Clyde',
        'Administrator'
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Bind trigger to auth.users table
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_admin_user();

-- Direct SQL Query: View and verify existing administrator accounts
SELECT 
    u.id AS supabase_auth_id,
    COALESCE(p.username, 'Adminclyde') AS login_username,
    u.email AS mapped_admin_email,
    u.confirmed_at IS NOT NULL AS is_email_confirmed,
    u.created_at,
    u.last_sign_in_at
FROM auth.users u
LEFT JOIN public.admin_profiles p ON u.id = p.id
ORDER BY u.created_at DESC;

