    id BIGINT PRIMARY KEY DEFAULT 1,
    application_title TEXT NOT NULL DEFAULT 'BICOR-Product-Management',
    currency TEXT NOT NULL DEFAULT 'USD',
    admin_full_name TEXT DEFAULT 'Administrator Clyde',
    admin_email TEXT DEFAULT 'clyde@example.com',
